            *c_fields("DONGLE_CACHED_REPORT_ENVELOPE_", spec["cached_report_envelope"]),
            f"#define DONGLE_RPC_FAILURE_ERROR_OFFSET (DONGLE_RPC_OFFSET_PAYLOAD + {rpc['failure_error_payload_offset']})",
