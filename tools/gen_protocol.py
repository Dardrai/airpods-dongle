def rust_module(spec):
    """Wire constants only; host parsers keep their own admission and validation."""
    lines, depth = ["// " + NOTICE, "#![allow(dead_code)]", ""], 0

    def line(text=""):
        lines.append("    " * depth + text if text else "")

    def constant(name, value, kind=None):
        if kind is None:
            kind = "i32" if value < 0 else "u32" if value > 255 else "u8"
        line(f"pub const {ident(name)}: {kind} = {value};")

    def open_module(name):
        nonlocal depth
        line(f"pub mod {name} {{")
        depth += 1

    def close_module():
        nonlocal depth
        depth -= 1
        line("}")
        line()

    def fields(items):
        for item in items:
            constant(item["name"] + "_offset", item["offset"], "usize")
            constant(item["name"] + "_size", item["size"], "usize")

    def values(name, items, kind=None, flags=False):
        open_module(name)
        for item in items:
            constant(item["name"], item["value"], kind)
        if flags:
            constant("undefined_bits", 0xff & ~sum(item["value"] for item in items), "u8")
        close_module()

    magic = list(spec["magic"].encode())
    line(f"pub const MAGIC: [u8; {len(magic)}] = {magic};")
    constant("protocol_version", spec["protocol_version"])
    open_module("frame")
    constant("size", spec["frame"]["size"], "usize")
    fields(spec["frame"]["header"])
    constant("header_size", sum(f["size"] for f in spec["frame"]["header"]), "usize")
    close_module()
    for name in ("control", "rpc"):
        section = spec[name]
        open_module(name)
        constant("report_id", section["report_id"])
        header = [section["report_id"], *magic, spec["protocol_version"], spec["frame"]["size"]]
        line(f"pub const HEADER: [u8; {len(header)}] = {header};")
        if name == "control":
            for module, item in (("command_field", section["command"]), ("status_field", section["status"])):
                open_module(module)
                fields(item["fields"])
                close_module()
            values("opcode", section["command"]["opcodes"])
            values("status_flag", section["status"]["flags"], flags=True)
            values("capability", section["status"]["capabilities"], "u16")
            values("listening_mode", section["listening_modes"])
            values("codec", section["codecs"])
            values("result", [v for v in section["results"] if not v.get("internal")])
            for key in ("battery_unknown", "age_unknown", "age_saturated"):
                constant(key, section["status"][key])
            open_module("component")
            for item in section["components"]:
                constant(item["name"] + "_slot", item["slot"], "usize")
                constant(item["name"] + "_bit", item["bit"])
            constant("slot_count", len(section["components"]), "usize")
            constant("undefined_bits", 0xff & ~sum(c["bit"] for c in section["components"]))
            close_module()
        else:
            open_module("field")
            fields(section["fields"])
            payload = by_name(section["fields"])["payload"]["offset"]
            constant("error_offset", payload + section["failure_error_payload_offset"], "usize")
            close_module()
            for module, key in (("operation", "operations"), ("phase", "phases"), ("error", "errors")):
                values(module, section[key])
            for key in ("maximum_fragment_length", "maximum_payload_length"):
                constant(key, section[key], "usize")
        close_module()
    for module, key in (("feature", "features"), ("settings_lease_action", "settings_lease_actions"),
                        ("reconnect_policy", "reconnect_policies"), ("firmware_variant", "firmware_variants"),
                        ("cached_slot", "cached_slots"), ("input_ownership", "input_ownerships")):
        values(module, spec[key])
    constant("settings_lease_response_version", spec["settings_lease_response_version"])
    open_module("cached_report")
    fields(spec["cached_report_envelope"])
    constant("envelope_size", spec["cached_report_envelope_size"], "usize")
    close_module()
    open_module("settings_snapshot")
    for key in ("version", "header_size", "record_size"):
        constant(key, spec["settings_snapshot"][key], "u8" if key == "version" else "usize")
    fields(spec["settings_snapshot"]["header"])
    fields(spec["settings_snapshot"]["record"])
    constant("extended_selector", by_name(spec["settings_snapshot_selectors"])["extended"]["selector"])
    close_module()
    open_module("setting")
    line(f"pub const IDS: [u8; {len(spec['settings'])}] = {[s['id'] for s in spec['settings']]};")
    for setting in spec["settings"]:
        open_module(setting["name"])
        constant("id", setting["id"])
        for item in setting["domain"].get("values", []):
            constant(item["name"], item["value"], "u32")
        close_module()
    close_module()
    for layout in spec["layouts"]:
        open_module(layout["name"])
        for key in ("version", "size", "request_size"):
            if key in layout:
                constant(key, layout[key], "u8" if key == "version" else "usize")
        fields(layout["fields"])
        for item in layout.get("constants", []):
            constant(item["name"], item["value"])
        for group in layout.get("groups", []):
            values(group["name"], group["values"], flags=group.get("flags", False))
        close_module()
    open_module("usb")
    usb = spec["usb"]
    for key in ("vendor_id", "vendor_usage_page", "vendor_usage", "report_size_bits", "report_count"):
        constant(key, usb[key], "u16")
    for item in usb["products"]:
        constant(item["name"] + "_product_id", item["value"], "u16")
    close_module()
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------- C vectors (host tests only)

def layout_field_value(spec, layout, field, value):
    """Resolve a vector's field value: an integer, a value name, or a list of flag names."""
    groups = {g["name"]: g for g in layout.get("groups", [])}
    if isinstance(value, int):
        return value
    if isinstance(value, list):
        flags = next(g for g in layout["groups"] if g.get("flags"))
        return sum(by_name(flags["values"])[name]["value"] for name in value)
    shared = {"actual_codec": spec["control"]["codecs"], "input_ownership": spec["input_ownerships"]}
    for other in spec["layouts"]:  # request layouts reuse their response's value groups
        for group in other.get("groups", []):
            shared.setdefault(group["name"], group["values"])
    values = groups[field]["values"] if field in groups else shared[field]
    return by_name(values)[value]["value"]


def vectors_c(spec, vectors):
    """Flatten vectors.json into C initializers, resolving spec names to numbers."""
    control, rpc = spec["control"], spec["rpc"]
    settings = by_name(spec["settings"])

    def value_of(group, name):
        return name if isinstance(name, int) else by_name(group)[name]["value"]

    def blob(hex_text):
        data = bytes.fromhex(hex_text)
        return "(const uint8_t[]){" + (",".join(str(b) for b in data) or "0") + "}," + str(len(data))

    def array(values, suffix=""):
        return "{" + ",".join(f"{v}{suffix}" for v in values) + "}"

    def boolean(value):
        return "true" if value else "false"

    def setting_value(setting, value):
        return value_of(setting["domain"]["values"], value) if isinstance(value, str) else value

    out = ["// Generated from protocol/vectors.json by tools/gen_protocol.py --vectors-c. Host tests only.",
           "#include <stdbool.h>", "#include <stdint.h>", ""]
    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool valid; uint8_t opcode;"
               " uint32_t connection_generation; uint8_t selected_address[6]; uint32_t command_sequence;"
               " uint8_t argument; } command_vector_t;")
    out.append("static const command_vector_t command_vectors[] = {")
    for v in vectors["control_commands"]:
        f = v.get("fields")
        fields = (f"{value_of(control['command']['opcodes'], f['opcode'])},{f['connection_generation']}u,"
                  f"{array(bytes.fromhex(f['selected_address']))},{f['command_sequence']}u,{f['argument']}"
                  if f else "0,0u,{0},0u,0")
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{boolean(v['valid'])},{fields}}},")
    out.append("};")

    status = control["status"]
    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t flags;"
               " uint32_t connection_generation; uint8_t selected_address[6], listening_mode, battery_percent[3],"
               " charging_components, output_codec; uint32_t battery_ages_milliseconds[3], last_command_sequence;"
               " uint8_t last_command_result, last_command_opcode; uint16_t capabilities;"
               " uint8_t present_components, case_observed_components; } status_vector_t;")
    out.append("static const status_vector_t status_vectors[] = {")
    for v in vectors["control_status"]:
        f = v["fields"]
        out.append(
            f"    {{{json.dumps(v['name'])},{blob(v['hex'])},"
            f"{sum(value_of(status['flags'], n) for n in f['flags'])},{f['connection_generation']}u,"
            f"{array(bytes.fromhex(f['selected_address']))},{value_of(control['listening_modes'], f['listening_mode'])},"
            f"{array(f['battery_percent'])},{f['charging_components']},{value_of(control['codecs'], f['output_codec'])},"
            f"{array(f['battery_ages_milliseconds'], 'u')},{f['last_command_sequence']}u,"
            f"{value_of(control['results'], f['last_command_result'])},{f['last_command_opcode']},"
            f"{sum(value_of(status['capabilities'], n) for n in f['capabilities'])},"
            f"{f['present_components']},{f['case_observed_components']}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool request_valid;"
               " uint8_t operation; uint32_t connection_generation, transaction_sequence; uint16_t total_length,"
               " fragment_offset; uint8_t fragment_length, response_phase; const uint8_t *payload;"
               " unsigned payload_size; } rpc_vector_t;")
    out.append("static const rpc_vector_t rpc_vectors[] = {")
    for v in vectors["rpc_frames"]:
        f = v["fields"]
        out.append(
            f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{boolean(v['request_valid'])},"
            f"{value_of(rpc['operations'], f['operation'])},{f['connection_generation']}u,{f['transaction_sequence']}u,"
            f"{f['total_length']},{f['fragment_offset']},{f['fragment_length']},"
            f"{value_of(rpc['phases'], f['response_phase'])},{blob(f['payload'])}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t feature;"
               " bool writes_setting; uint8_t setting; uint32_t value; } feature_vector_t;")
    out.append("static const feature_vector_t feature_vectors[] = {")
    for v in vectors["features"]:
        s = settings.get(v.get("setting", ""))
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['payload'])},{value_of(spec['features'], v['feature'])},"
                   f"{boolean(s)},{s['id'] if s else 0},{setting_value(s, v['value']) if s else 0}u}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t listening_mode,"
               " battery_percent[3], charging_components; bool known[3]; } readback_vector_t;")
    out.append("static const readback_vector_t readback_vectors[] = {")
    for v in vectors["aacp_readback"]:
        x = v["expect"]
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},"
                   f"{value_of(control['listening_modes'], x['listening_mode'])},{array(x['battery_percent'])},"
                   f"{x['charging_components']},{array(boolean(k) for k in x['known'])}}},")
    out.append("};")

    out.append("typedef struct { const uint8_t *data; unsigned size; uint32_t at; } timed_packet_t;")
    out.append("typedef struct { const char *name; const timed_packet_t *packets; unsigned count; uint32_t now;"
               " bool extended; const uint8_t *snapshot; unsigned snapshot_size; } session_vector_t;")
    out.append("static const session_vector_t session_vectors[] = {")
    for v in vectors["settings_sessions"]:
        packets = ",".join(f"{{{blob(p['hex'])},{p['at']}u}}" for p in v["packets"])
        out.append(f"    {{{json.dumps(v['name'])},(const timed_packet_t[]){{{packets}}},{len(v['packets'])},"
                   f"{v['now']}u,{boolean(v['extended'])},{blob(v['snapshot'])}}},")
    out.append("};")

    out.append("typedef struct { uint8_t setting; uint32_t value; bool valid; } value_vector_t;")
    out.append("static const value_vector_t value_vectors[] = {")
    for v in vectors["setting_values"]:
        s = settings[v["setting"]]
        for valid in (True, False):
            for value in v["valid" if valid else "invalid"]:
                out.append(f"    {{{s['id']},{setting_value(s, value)}u,{boolean(valid)}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool valid;"
               " unsigned requests; } phone_vector_t;")
    out.append("static const phone_vector_t phone_vectors[] = {")
    for v in vectors["phone_frames"]:
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{boolean(v['valid'])},{v['requests']}}},")
    out.append("};")
    out.append("typedef struct { unsigned offset, size; uint32_t value; } layout_field_t;")
    out.append("typedef struct { const char *name, *layout; const uint8_t *data; unsigned size, expected_size;"
               " const layout_field_t *fields; unsigned count; bool checks_validity, valid; } layout_vector_t;")
    out.append("static const layout_vector_t layout_vectors[] = {")
    layouts = by_name(spec["layouts"])
    for v in vectors["layouts"]:
        layout = layouts[v["layout"]]
        prefix = "DONGLE_" + ident(layout["name"]) + "_"
        fields = by_name(layout["fields"])
        entries = []
        for name, value in v["fields"].items():
            f = fields[name]
            size = f"{prefix}SIZE_{ident(name)}" if f["size"] != 1 else "1"
            raw = layout_field_value(spec, layout, name, value) & ((1 << (8 * f["size"])) - 1)
            entries.append(f"{{{prefix}OFFSET_{ident(name)},{size},{raw}u}}")
        expected = prefix + ("SIZE" if "size" in layout else "REQUEST_SIZE")
        out.append(f"    {{{json.dumps(v['name'])},{json.dumps(layout['name'])},{blob(v['hex'])},{expected},"
                   f"(const layout_field_t[]){{{','.join(entries)}}},{len(entries)},"
                   f"{boolean('valid' in v)},{boolean(v.get('valid', True))}}},")
    out.append("};")
    out.append("#define VECTOR_COUNT(a) (sizeof(a) / sizeof((a)[0]))")
    return "\n".join(out) + "\n"


def outputs(spec):
    return {C_HEADER: c_header(spec), C_SETTINGS: c_settings(spec), PYTHON: py_module(spec),
            KOTLIN: kotlin_module(spec), RUST: rust_module(spec)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if committed outputs are stale")
    parser.add_argument("--vectors-c", metavar="PATH", help="write vectors.json as a C include")
    parser.add_argument("--kotlin", metavar="PATH", help="write the Kotlin object to PATH instead of the sample")
    parser.add_argument("--kotlin-package", default=KOTLIN_PACKAGE, help=f"Kotlin package (default {KOTLIN_PACKAGE})")
    parser.add_argument("--kotlin-object", default=KOTLIN_OBJECT, help=f"Kotlin object name (default {KOTLIN_OBJECT})")
    args = parser.parse_args(argv)
    spec = load()
    check_spec(spec)
    if args.vectors_c:
        pathlib.Path(args.vectors_c).write_text(vectors_c(spec, load(VECTORS)), encoding="utf-8")
        return 0
    if args.kotlin:
        pathlib.Path(args.kotlin).write_text(kotlin_module(spec, args.kotlin_package, args.kotlin_object),
                                             encoding="utf-8")
        return 0
    stale = []
    for path, text in outputs(spec).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated protocol files (run python3 tools/gen_protocol.py): "
              + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
