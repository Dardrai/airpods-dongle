NOTICE = "Generated by tools/gen_protocol.py from protocol/dongle-protocol.json. Do not edit."


def load(path=SPEC):
    return json.loads(path.read_text(encoding="utf-8"))


def ident(name):
    return name.upper().replace("-", "_")


def by_name(items):
    return {item["name"]: item for item in items}


def check_spec(spec):
    """Reject specs that would silently change catalog bit positions or collide."""
    settings = spec["settings"]
    if [s["index"] for s in settings] != list(range(len(settings))):
        raise ValueError("setting indices must be 0..n-1 in catalog order")
    if len(settings) > 32:
        raise ValueError("model capability masks are 32-bit")
    for key in ("id", "name", "cli"):
        values = [s[key] for s in settings]
        if len(set(values)) != len(values):
            raise ValueError(f"duplicate setting {key}")
    if sorted(spec["cli"]["settings_order"]) != sorted(s["cli"] for s in settings):
        raise ValueError("cli.settings_order must list every setting once")
    names = {s["name"] for s in settings}
    for profile in spec["profiles"]:
        if not 1 <= len(profile["models"]) <= spec["profile_model_slots"]:
            raise ValueError("profile model count")
        unknown = set(profile["controls"]) - names
        if unknown:
            raise ValueError(f"unknown profile controls: {sorted(unknown)}")
    if spec["case_battery_profile_model"] not in [p["models"][0] for p in spec["profiles"]]:
        raise ValueError("case_battery_profile_model must be the first model of a profile")
    for group in (spec["control"]["results"], spec["rpc"]["errors"], spec["features"],
                  spec["rpc"]["operations"], spec["control"]["command"]["opcodes"]):
        values = [item["value"] for item in group]
        if len(set(values)) != len(values):
            raise ValueError("duplicate enumerated value")


def profile_mask(spec, profile):
    index = {s["name"]: s["index"] for s in spec["settings"]}
    return sum(1 << index[name] for name in profile["controls"])


# ---------------------------------------------------------------- C header

def c_string(data):
    if all(chr(b).isalnum() for b in data):
        return '"' + bytes(data).decode() + '"'
    return "".join('"\\x%02x"' % b for b in data)


def c_value_test(domain, var="value"):
    kind = domain["kind"]
    if kind in ("enum", "toggle"):
        return " || ".join(f"{var}==0x{v['value']:x}u" for v in domain["values"])
    if kind == "percent":
        if "flag" in domain:
            return f"({var}&~0xffu)==0x{domain['flag']:x}u && ({var}&0xffu)<={domain['max']}u"
        return f"{var}<={domain['max']}u"
    if kind == "mode_mask":
        mask = 0
        for v in domain["values"]:
            mask |= v["value"]
        return f"({var}&~0x{mask:x}u)==0 && dongle_bit_count({var})>={domain['min_bits']}u"
    if kind == "action_pair":
        def side(expr):
            return "(" + " || ".join(f"{expr}==0x{v['value']:x}u" for v in domain["values"]) + ")"
        width = 8 * len(domain["sides"])
        tests = [f"{var}<=0x{(1 << width) - 1:x}u"]
        for i in range(len(domain["sides"])):
            tests.append(side(f"(({var}>>{8 * i})&0xffu)" if i else f"({var}&0xffu)"))
        return " && ".join(tests)
    raise ValueError("unknown domain kind " + kind)


def c_defines(prefix, items, fmt="{}"):
    return [f"#define {prefix}{ident(i['name'])} {fmt.format(i['value'])}" for i in items]


def c_fields(prefix, fields):
    lines = []
    for f in fields:
        lines.append(f"#define {prefix}{ident(f['name'])}_OFFSET {f['offset']}")
        if f["size"] != 1:
            lines.append(f"#define {prefix}{ident(f['name'])}_SIZE {f['size']}")
    return lines


def c_header(spec):
    control, rpc, phone, aacp = spec["control"], spec["rpc"], spec["phone_transport"], spec["aacp"]
    out = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// " + NOTICE,
        "#ifndef DONGLE_PROTOCOL_SPEC_H",
        "#define DONGLE_PROTOCOL_SPEC_H",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        "",
        "// Frame header shared by report 2, report 3 and the phone transport payload.",
        f"#define DONGLE_PROTOCOL_VERSION {spec['protocol_version']}",
        f"#define DONGLE_MAGIC {c_string(spec['magic'].encode())}",
        f"#define DONGLE_MAGIC_SIZE {len(spec['magic'])}",
        f"#define DONGLE_REPORT_SIZE {spec['frame']['size']}",
        *c_fields("DONGLE_HEADER_", spec["frame"]["header"]),
        "",
        "// Report 2: basic control command and status.",
        f"#define DONGLE_REPORT_ID {control['report_id']}",
        *c_fields("DONGLE_CMD_", control["command"]["fields"]),
        *c_defines("DONGLE_OP_", control["command"]["opcodes"]),
        *c_fields("DONGLE_STATUS_", control["status"]["fields"]),
        *c_defines("DONGLE_FLAG_", control["status"]["flags"]),
        *c_defines("DONGLE_CAP_", control["status"]["capabilities"], "0x{:x}u"),
        f"#define DONGLE_BATTERY_UNKNOWN {control['status']['battery_unknown']}",
        f"#define DONGLE_AGE_UNKNOWN 0x{control['status']['age_unknown']:x}u",
        f"#define DONGLE_AGE_SATURATED 0x{control['status']['age_saturated']:x}u",
    ]
    for c in control["components"]:
        out.append(f"#define DONGLE_COMPONENT_{ident(c['name'])} {c['slot']}")
        out.append(f"#define DONGLE_COMPONENT_{ident(c['name'])}_BIT {c['bit']}")
    out += c_defines("DONGLE_LISTENING_", control["listening_modes"])
    out += c_defines("DONGLE_CODEC_", control["codecs"])
    out.append("enum {")
    out += [f"    DONGLE_RESULT_{ident(r['name'])} = {r['value']},"
            + ("  // internal; never published in report 2" if r.get("internal") else "")
            for r in control["results"]]
    out += ["};", "",
            "// Report 3: fragmented settings RPC.",
            f"#define DONGLE_RPC_REPORT_ID {rpc['report_id']}",
            f"#define DONGLE_RPC_CHUNK {rpc['chunk']}u",
            f"#define DONGLE_RPC_PAYLOAD_LIMIT {rpc['payload_limit']}u",
            *c_fields("DONGLE_RPC_", rpc["fields"]),
            *c_defines("DONGLE_RPC_OP_", rpc["operations"]),
            "enum {",
            *[f"    DONGLE_RPC_PHASE_{ident(p['name'])} = {p['value']}," for p in rpc["phases"]],
            "};",
            "enum {",
            *[f"    DONGLE_RPC_ERROR_{ident(e['name'])} = {e['value']}," for e in rpc["errors"]],
            "};",
            "",
            "// Phone RFCOMM transport framing around reports 2 and 3.",
            f"#define DONGLE_PHONE_HEADER_SIZE {phone['header_size']}u",
            f"#define DONGLE_PHONE_FRAME_MAX {phone['frame_max']}u",
            *c_fields("DONGLE_PHONE_", phone["fields"]),
            *c_defines("DONGLE_PHONE_OP_", phone["operations"]),
            f"#define DONGLE_PHONE_RESPONSE_FLAG 0x{phone['response_flag']:x}",
            f"#define DONGLE_PHONE_ERROR_OPERATION 0x{phone['error_operation']:x}",
            *c_defines("DONGLE_PHONE_ERROR_", phone["errors"]),
            "",
            "// Typed feature requests (RPC operation 7) and their small payload enums.",
            *[f"#define DONGLE_FEATURE_{ident(f['name'])} {f['value']}"
              + ("  // reserved" if f.get("reserved") else "") for f in spec["features"]],
            *c_defines("DONGLE_LEASE_", spec["lease_actions"]),
            f"#define DONGLE_LEASE_RESPONSE_VERSION {spec['lease_response_version']}",
            *c_defines("DONGLE_RECONNECT_", spec["reconnect_policies"]),
            *c_defines("DONGLE_VARIANT_", spec["firmware_variants"], "{}u"),
            *c_defines("DONGLE_CACHED_", spec["cached_slots"]),
            f"#define DONGLE_CACHED_ENVELOPE_SIZE {spec['cached_envelope_size']}u",
            f"#define DONGLE_SETTINGS_SNAPSHOT_VERSION {spec['settings_snapshot']['version']}",
            f"#define DONGLE_SETTINGS_SNAPSHOT_HEADER_SIZE {spec['settings_snapshot']['header_size']}u",
            f"#define DONGLE_SETTINGS_SNAPSHOT_RECORD_SIZE {spec['settings_snapshot']['record_size']}u",
            *c_fields("DONGLE_SETTINGS_RECORD_", spec["settings_snapshot"]["record"]),
            f"#define DONGLE_SETTINGS_SNAPSHOT_EXTENDED {by_name(spec['settings_snapshot_selectors'])['extended']['selector']}",
            "",
            "// AirPods AACP framing used by the setting, readback and cache paths.",
            f"#define AACP_HEADER {c_string(aacp['header'])}",
            f"#define AACP_HEADER_SIZE {len(aacp['header'])}u",
            "#define AACP_HEADER_BYTES " + ",".join(f"0x{b:02x}" for b in aacp["header"]),
            f"#define AACP_OPCODE_OFFSET {aacp['opcode_offset']}",
            *c_defines("AACP_OP_", aacp["opcodes"], "0x{:02x}"),
            f"#define AACP_CONTROL_HEADER {c_string(aacp['header'] + [by_name(aacp['opcodes'])['control']['value'], 0])}",
            f"#define AACP_CONTROL_HEADER_SIZE {len(aacp['header']) + 2}u",
            f"#define AACP_CONTROL_PACKET_SIZE {aacp['control_packet_size']}u",
            f"#define AACP_CONTROL_ID_OFFSET {aacp['control_id_offset']}",
            f"#define AACP_CONTROL_VALUE_OFFSET {aacp['control_value_offset']}",
            *c_defines("AACP_CONTROL_", aacp["controls"], "0x{:02x}"),
            f"#define AACP_BATTERY_COUNT_OFFSET {aacp['battery']['count_offset']}",
            f"#define AACP_BATTERY_ENTRIES_OFFSET {aacp['battery']['entries_offset']}",
            f"#define AACP_BATTERY_ENTRY_SIZE {aacp['battery']['entry_size']}u",
            *c_fields("AACP_BATTERY_", aacp["battery"]["entry"]),
            *c_defines("AACP_BATTERY_", aacp["battery"]["components"]),
            f"#define AACP_BATTERY_LEVEL_UNKNOWN {aacp['battery']['level_unknown']}",
            *c_defines("AACP_BATTERY_STATUS_", aacp["battery"]["statuses"]),
            "",
            "// AirPods setting (AACP control) IDs, catalog order. Value names follow each domain.",
            ]
    for s in spec["settings"]:
        name = "DONGLE_SETTING_" + ident(s["name"])
        out.append(f"#define {name} 0x{s['id']:02x}")
        d = s["domain"]
        for v in d.get("values", []):
            out.append(f"#define {name}_{ident(v['name'])} 0x{v['value']:x}u")
        if d["kind"] == "percent":
            out.append(f"#define {name}_MAX {d['max']}u")
            if "flag" in d:
                out.append(f"#define {name}_FLAG 0x{d['flag']:x}u")
        if d["kind"] == "mode_mask":
            out.append(f"#define {name}_MIN_BITS {d['min_bits']}u")
        if "report_mask" in d:
            out.append(f"#define {name}_REPORT_MASK 0x{d['report_mask']:x}u")
    out += [f"#define DONGLE_LEGACY_SETTING_COUNT {spec['settings_legacy_count']}u", "",
            "static inline unsigned dongle_bit_count(uint32_t value) {",
            "    unsigned bits=0;",
            "    for (; value; value>>=1) bits+=value&1u;",
            "    return bits;",
            "}",
            "// Value domain from the spec; model gating is separate (dongle_settings.h).",
            "static inline bool dongle_setting_value_valid(uint8_t id, uint32_t value) {",
            "    switch(id) {"]
    for s in spec["settings"]:
        out.append(f"        case DONGLE_SETTING_{ident(s['name'])}: return {c_value_test(s['domain'])};")
    out += ["        default: return false;", "    }", "}"]
    for flag, comment in (("explicit_choice", "Writable for a known model before any device report."),
                          ("unknown_model", "Writable while the model is unknown.")):
        out += [f"// {comment}",
                f"static inline bool dongle_setting_{flag}(uint8_t id) {{",
                "    switch(id) {"]
        out += [f"        case DONGLE_SETTING_{ident(s['name'])}:" for s in spec["settings"] if s[flag]]
        out += ["            return true;", "        default: return false;", "    }", "}"]
    out += ["#endif", ""]
    return "\n".join(out)


def c_settings(spec):
    flags = spec["profile_flags"]
    slots = spec["profile_model_slots"]
    out = [
        "// SPDX-License-Identifier: GPL-3.0-only",
        "// " + NOTICE,
        "#ifndef DONGLE_SETTINGS_SPEC_H",
        "#define DONGLE_SETTINGS_SPEC_H",
        "#include <stdbool.h>",
        "#include <stdint.h>",
        '#include "../tinyusb/dongle_protocol_spec.h"',
        "",
        "// Catalog index is the bit position in setting_profile_t.controls; append only.",
        "static const uint8_t setting_ids[] = {",
    ]
    for s in spec["settings"]:
        out.append(f"    DONGLE_SETTING_{ident(s['name'])}, // bit {s['index']}")
    out += ["};",
            "#define DONGLE_SETTING_COUNT (sizeof(setting_ids) / sizeof(setting_ids[0]))",
            "typedef struct {",
            f"    uint16_t models[{slots}];",
            "    uint32_t controls;",
            "    bool " + ", ".join(flags) + ";",
            "} setting_profile_t;",
            "// Value validation and model masks mirror NTPods device_settings/device-models.",
            "static const setting_profile_t setting_profiles[] = {"]
    for p in spec["profiles"]:
        models = ",".join(str(m) for m in p["models"] + [0] * (slots - len(p["models"])))
        bools = ",".join("true" if p[f] else "false" for f in flags)
        out.append(f"    {{{{{models}}},0x{profile_mask(spec, p):08x},{bools}}},")
    out += ["};",
            "// Case BLE battery keys are used only for the profile whose first model is this.",
            f"#define DONGLE_CASE_BATTERY_PROFILE_MODEL {spec['case_battery_profile_model']}",
            "#endif", ""]
    return "\n".join(out)


# ---------------------------------------------------------------- Python module

def py_map(items, key="value"):
    return "{" + ", ".join(f"{i['name']!r}: {i[key]!r}" for i in items) + "}"


def py_module(spec):
    control, rpc, phone, aacp = spec["control"], spec["rpc"], spec["phone_transport"], spec["aacp"]
    settings = by_name(spec["settings"])
    by_cli = {s["cli"]: s for s in spec["settings"]}

    def fields(items):
        return "{" + ", ".join(f"{f['name']!r}: ({f['offset']}, {f['size']})" for f in items) + "}"

    def cli_kind(s):
        d = s["domain"]
        if d["kind"] in ("enum", "toggle"):
            return py_map(d["values"])
        return {"percent": "'percent'", "mode_mask": "'modes'", "action_pair": "'actions'"}[d["kind"]]

    out = [
        f'"""{NOTICE}"""',
        "",
        f"PROTOCOL_VERSION = {spec['protocol_version']}",
        f"MAGIC = {spec['magic'].encode()!r}",
        f"REPORT_SIZE = {spec['frame']['size']}",
        f"HEADER_FIELDS = {fields(spec['frame']['header'])}",
        "",
        f"CONTROL_REPORT_ID = {control['report_id']}",
        f"COMMAND_FIELDS = {fields(control['command']['fields'])}",
        f"OPCODES = {py_map(control['command']['opcodes'])}",
        "OPCODE_ARGUMENTS = {" + ", ".join(f"{o['value']}: {tuple(o['arguments'])!r}"
                                           for o in control["command"]["opcodes"]) + "}",
        f"STATUS_FIELDS = {fields(control['status']['fields'])}",
        f"STATUS_FLAGS = {py_map(control['status']['flags'])}",
        f"CAPABILITIES = {py_map(control['status']['capabilities'])}",
        f"COMPONENTS = {py_map(control['components'], 'bit')}",
        f"LISTENING_MODES = {py_map(control['listening_modes'])}",
        f"CODECS = {py_map(control['codecs'])}",
        f"RESULTS = {py_map(control['results'])}",
        f"BATTERY_UNKNOWN = {control['status']['battery_unknown']}",
        f"AGE_UNKNOWN = 0x{control['status']['age_unknown']:x}",
        "",
        f"RPC_REPORT_ID = {rpc['report_id']}",
        f"RPC_CHUNK = {rpc['chunk']}",
        f"RPC_PAYLOAD_LIMIT = {rpc['payload_limit']}",
        f"RPC_FIELDS = {fields(rpc['fields'])}",
        f"RPC_OPERATIONS = {py_map(rpc['operations'])}",
        f"RPC_PHASES = {py_map(rpc['phases'])}",
        f"RPC_ERRORS = {py_map(rpc['errors'])}",
        "",
        f"PHONE_HEADER_SIZE = {phone['header_size']}",
        f"PHONE_OPERATIONS = {py_map(phone['operations'])}",
        f"PHONE_RESPONSE_FLAG = 0x{phone['response_flag']:x}",
        f"PHONE_ERROR_OPERATION = 0x{phone['error_operation']:x}",
        f"PHONE_ERRORS = {py_map(phone['errors'])}",
        "",
        f"FEATURES = {py_map(spec['features'])}",
        f"LEASE_ACTIONS = {py_map(spec['lease_actions'])}",
        f"RECONNECT_POLICIES = {py_map(spec['reconnect_policies'])}",
        f"FIRMWARE_VARIANTS = {py_map(spec['firmware_variants'])}",
        f"CACHED_SLOTS = {py_map(spec['cached_slots'])}",
        f"SNAPSHOT_VERSION = {spec['settings_snapshot']['version']}",
        f"SNAPSHOT_RECORD_SIZE = {spec['settings_snapshot']['record_size']}",
        f"SNAPSHOT_EXTENDED = {by_name(spec['settings_snapshot_selectors'])['extended']['selector']}",
        "",
        f"AACP_HEADER = {bytes(aacp['header'])!r}",
        f"AACP_OPCODES = {py_map(aacp['opcodes'])}",
        "",
        "# Setting (AACP control) IDs in catalog order; the index is the model-mask bit.",
        "SETTING_IDS = {" + ", ".join(f"{s['name']!r}: 0x{s['id']:02x}" for s in spec["settings"]) + "}",
        f"LEGACY_SETTING_COUNT = {spec['settings_legacy_count']}",
        "EXTENDED_SETTINGS = frozenset({" + ", ".join(
            f"0x{s['id']:02x}" for s in spec["settings"] if s["index"] >= spec["settings_legacy_count"]) + "})",
        "SETTING_DOMAINS = {" + ", ".join(f"0x{s['id']:02x}: {s['domain']!r}" for s in spec["settings"]) + "}",
        "EXPLICIT_CHOICE = frozenset({" + ", ".join(
            f"0x{s['id']:02x}" for s in spec["settings"] if s["explicit_choice"]) + "})",
        "UNKNOWN_MODEL = frozenset({" + ", ".join(
            f"0x{s['id']:02x}" for s in spec["settings"] if s["unknown_model"]) + "})",
        "PROFILES = (",
        *[f"    {{'models': {tuple(p['models'])!r}, 'controls': 0x{profile_mask(spec, p):08x}, "
          + ", ".join(f"{f!r}: {p[f]!r}" for f in spec["profile_flags"]) + "}," for p in spec["profiles"]],
        ")",
        "",
        "# CLI view: name -> (control ID, named values or value kind), in CLI display order.",
        "SETTINGS = {",
        *[f"    {cli!r}: (0x{by_cli[cli]['id']:02x}, {cli_kind(by_cli[cli])})," for cli in spec["cli"]["settings_order"]],
        "}",
        f"TOGGLE = {py_map(settings['one_bud_anc']['domain']['values'])}",
        f"HOLD_ACTIONS = {py_map(settings['hold_actions']['domain']['values'])}",
        f"HOLD_MODE_BITS = {py_map(settings['hold_modes']['domain']['values'])}",
        f"HOLD_MODE_MIN_BITS = {settings['hold_modes']['domain']['min_bits']}",
        "PERCENT_FLAGS = {" + ", ".join(f"0x{s['id']:02x}: 0x{s['domain']['flag']:x}" for s in spec["settings"]
                                         if s["domain"]["kind"] == "percent" and "flag" in s["domain"]) + "}",
        "",
        "",
        "def setting_value_valid(control, value):",
        '    """Value-domain check matching dongle_setting_value_valid() in the firmware."""',
        "    domain = SETTING_DOMAINS.get(control)",
        "    if domain is None or not 0 <= value <= 0xffffffff:",
        "        return False",
        "    kind = domain['kind']",
        "    if kind in ('enum', 'toggle'):",
        "        return any(value == item['value'] for item in domain['values'])",
        "    if kind == 'percent':",
        "        flag = domain.get('flag', 0)",
        "        low = value & 0xff if flag else value",
        "        return value - low == flag and low <= domain['max']",
        "    if kind == 'mode_mask':",
        "        mask = sum(item['value'] for item in domain['values'])",
        "        return not value & ~mask and bin(value).count('1') >= domain['min_bits']",
        "    if kind == 'action_pair':",
        "        allowed = {item['value'] for item in domain['values']}",
        "        sides = len(domain['sides'])",
        "        return value < 1 << (8 * sides) and all((value >> (8 * i)) & 0xff in allowed for i in range(sides))",
        "    return False",
        "",
    ]
    return "\n".join(wrap_py(line) for line in out)


def wrap_py(line, limit=100):
    """Put each entry of a long generated dict literal on its own line."""
    name, sep, literal = line.partition(" = ")
    if len(line) <= limit or not sep or not name.isupper() or not literal.startswith("{"):
        return line
    entries = ast.literal_eval(literal)
    body = "".join(f"    {f'0x{k:02x}' if isinstance(k, int) else repr(k)}: {v!r},\n" for k, v in entries.items())
    return f"{name} = {{\n{body}}}"


# ---------------------------------------------------------------- C vectors (host tests only)

def vectors_c(spec, vectors):
    """Flatten vectors.json into C initializers, resolving names through the spec."""
    settings = by_name(spec["settings"])
    features = by_name(spec["features"])

    def blob(hex_text):
        data = bytes.fromhex(hex_text)
        return "(const uint8_t[]){" + (",".join(str(b) for b in data) or "0") + "}," + str(len(data))

    def setting_value(setting, value):
        if isinstance(value, int):
            return value
        values = by_name(setting["domain"]["values"])
        return values[value]["value"]

    out = ["// Generated from protocol/vectors.json by tools/gen_protocol.py --vectors-c.",
           "#include <stdbool.h>", "#include <stdint.h>", ""]
    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool valid;"
               " uint8_t opcode, argument; uint32_t generation, sequence; } command_vector_t;")
    out.append("static const command_vector_t command_vectors[] = {")
    for v in vectors["control_commands"]:
        f = v.get("fields", {})
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{str(v['valid']).lower()},"
                   f"{f.get('opcode', 0)},{f.get('argument', 0)},{f.get('generation', 0)}u,{f.get('sequence', 0)}u}},")
    out.append("};")

    control = spec["control"]["status"]
    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t flags; uint32_t generation;"
               " uint8_t address[6], listening_mode, battery[3], charging, codec; uint32_t ages[3], last_sequence;"
               " uint8_t result, last_opcode; uint16_t capabilities; uint8_t present, case_source; } status_vector_t;")
    out.append("static const status_vector_t status_vectors[] = {")
    flags = by_name(control["flags"])
    caps = by_name(control["capabilities"])
    results = by_name(spec["control"]["results"])
    for v in vectors["control_status"]:
        f = v["fields"]
        out.append(
            f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{sum(flags[n]['value'] for n in f['flags'])},"
            f"{f['generation']}u,{{{','.join(str(b) for b in bytes.fromhex(f['address']))}}},"
            f"{by_name(spec['control']['listening_modes'])[f['listening_mode']]['value']},"
            f"{{{','.join(str(b) for b in f['battery'])}}},{f['charging']},"
            f"{by_name(spec['control']['codecs'])[f['codec']]['value']},"
            f"{{{','.join(str(a) + 'u' for a in f['battery_ages'])}}},{f['last_sequence']}u,"
            f"{results[f['result']]['value']},{f['last_opcode']},{sum(caps[n]['value'] for n in f['capabilities'])},"
            f"{f['present']},{f['case_source']}}},")
    out.append("};")

    rpc = spec["rpc"]
    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool request_valid;"
               " uint8_t operation; uint32_t generation, sequence; uint16_t total, offset; uint8_t length, phase;"
               " const uint8_t *payload; unsigned payload_size; } rpc_vector_t;")
    out.append("static const rpc_vector_t rpc_vectors[] = {")
    for v in vectors["rpc_frames"]:
        f = v["fields"]
        out.append(
            f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{str(v['request_valid']).lower()},"
            f"{by_name(rpc['operations'])[f['operation']]['value'] if isinstance(f['operation'], str) else f['operation']},"
            f"{f['generation']}u,{f['sequence']}u,{f['total']},{f['offset']},{f['length']},"
            f"{by_name(rpc['phases'])[f['phase']]['value']},{blob(f['payload'])}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t feature;"
               " uint8_t setting; uint32_t value; bool has_setting; } feature_vector_t;")
    out.append("static const feature_vector_t feature_vectors[] = {")
    for v in vectors["features"]:
        s = settings.get(v.get("setting", ""))
        value = setting_value(s, v["value"]) if s else 0
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['payload'])},{features[v['feature']]['value']},"
                   f"{s['id'] if s else 0},{value}u,{str(bool(s)).lower()}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; uint8_t listening_mode,"
               " battery[3], charging; bool known[3]; } readback_vector_t;")
    out.append("static const readback_vector_t readback_vectors[] = {")
    for v in vectors["aacp_readback"]:
        e = v["expect"]
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},"
                   f"{by_name(spec['control']['listening_modes'])[e['listening_mode']]['value']},"
                   f"{{{','.join(str(b) for b in e['battery'])}}},{e['charging']},"
                   f"{{{','.join(str(k).lower() for k in e['known'])}}}}},")
    out.append("};")

    out.append("typedef struct { const uint8_t *data; unsigned size; uint32_t at; } timed_packet_t;")
    out.append("typedef struct { const char *name; const timed_packet_t *packets; unsigned count; uint32_t now;"
               " bool extended; const uint8_t *snapshot; unsigned snapshot_size; } session_vector_t;")
    out.append("static const session_vector_t session_vectors[] = {")
    for v in vectors["settings_sessions"]:
        packets = ",".join(f"{{{blob(p['hex'])},{p['at']}u}}" for p in v["packets"])
        out.append(f"    {{{json.dumps(v['name'])},(const timed_packet_t[]){{{packets}}},{len(v['packets'])},"
                   f"{v['now']}u,{str(v['extended']).lower()},{blob(v['snapshot'])}}},")
    out.append("};")

    out.append("typedef struct { uint8_t setting; uint32_t value; bool valid; } value_vector_t;")
    out.append("static const value_vector_t value_vectors[] = {")
    for v in vectors["setting_values"]:
        s = settings[v["setting"]]
        for valid in (True, False):
            for value in v["valid" if valid else "invalid"]:
                out.append(f"    {{{s['id']},{setting_value(s, value)}u,{str(valid).lower()}}},")
    out.append("};")

    out.append("typedef struct { const char *name; const uint8_t *data; unsigned size; bool valid; unsigned requests; } phone_vector_t;")
    out.append("static const phone_vector_t phone_vectors[] = {")
    for v in vectors["phone_frames"]:
        out.append(f"    {{{json.dumps(v['name'])},{blob(v['hex'])},{str(v['valid']).lower()},{v['requests']}}},")
    out.append("};")
    out.append("#define VECTOR_COUNT(a) (sizeof(a) / sizeof((a)[0]))")
    return "\n".join(out) + "\n"


def outputs(spec):
    return {C_HEADER: c_header(spec), C_SETTINGS: c_settings(spec), PYTHON: py_module(spec)}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if committed outputs are stale")
    parser.add_argument("--vectors-c", metavar="PATH", help="write vectors.json as a C include")
    args = parser.parse_args(argv)
    spec = load()
    check_spec(spec)
    if args.vectors_c:
        pathlib.Path(args.vectors_c).write_text(vectors_c(spec, load(VECTORS)), encoding="utf-8")
        return 0
    stale = []
    for path, text in outputs(spec).items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("Stale generated protocol files (run python3 tools/gen_protocol.py): "
              + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
