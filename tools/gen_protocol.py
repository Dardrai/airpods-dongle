#!/usr/bin/env python3
"""Generate the dongle protocol bindings from protocol/dongle-protocol.json.

Outputs are committed so the firmware build needs no extra step:
  src/tinyusb/dongle_protocol_spec.h   named constants and setting validators
  src/btstack/dongle_settings_spec.h   setting catalog and per-model profiles
  tools/dongle_protocol.py             the same data for the Python tools

--check fails when a committed output differs from what the spec generates.
--vectors-c PATH writes protocol/vectors.json as a C include for the host tests.
Standard library only.
"""

