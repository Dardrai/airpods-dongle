def load(path=SPEC):
    return json.loads(path.read_text(encoding="utf-8"))


def ident(name):
    return name.upper().replace("-", "_")


def by_name(items):
    return {item["name"]: item for item in items}


def check_fields(label, fields, size=None):
    """Fields must be ordered, non-overlapping and, when a size is given, end inside it."""
    end = 0
    for f in fields:
        if f["offset"] < end or f["size"] < 1:
            raise ValueError(f"{label}: field {f['name']} overlaps or is empty")
        end = f["offset"] + f["size"]
    if size is not None and end > size:
        raise ValueError(f"{label}: fields run past {size} bytes")
    if len({f["name"] for f in fields}) != len(fields):
        raise ValueError(f"{label}: duplicate field name")


def check_spec(spec):
    """Reject specs that would silently change catalog bit positions or collide."""
    settings = spec["settings"]
    if [s["index"] for s in settings] != list(range(len(settings))):
        raise ValueError("setting indices must be 0..n-1 in catalog order")
    if len(settings) > 32:
        raise ValueError("model capability masks are 32-bit")
    for key in ("id", "name", "cli"):
        values = [s[key] for s in settings]
        if len(set(values)) != len(values):
            raise ValueError(f"duplicate setting {key}")
    if sorted(spec["cli"]["settings_order"]) != sorted(s["cli"] for s in settings):
        raise ValueError("cli.settings_order must list every setting once")
    names = {s["name"] for s in settings}
    for profile in spec["profiles"]:
        if not 1 <= len(profile["models"]) <= spec["profile_model_slots"]:
            raise ValueError("profile model count")
        unknown = set(profile["controls"]) - names
        if unknown:
            raise ValueError(f"unknown profile controls: {sorted(unknown)}")
    if spec["case_battery_profile_model"] not in [p["models"][0] for p in spec["profiles"]]:
        raise ValueError("case_battery_profile_model must be the first model of a profile")
    for group in (spec["control"]["results"], spec["rpc"]["errors"], spec["features"],
                  spec["rpc"]["operations"], spec["control"]["command"]["opcodes"]):
        values = [item["value"] for item in group]
        if len(set(values)) != len(values):
            raise ValueError("duplicate enumerated value")
    features = by_name(spec["features"])
    for layout in spec["layouts"]:
        size = layout.get("size", layout.get("request_size"))
        if ("size" in layout) == ("request_size" in layout):
            raise ValueError(f"layout {layout['name']}: exactly one of size and request_size")
        check_fields("layout " + layout["name"], layout["fields"], size)
        if "request_size" in layout:
            feature = features[layout["feature"]]
            if feature.get("request_size") != layout["request_size"] or layout["fields"][0]["name"] != "feature":
                raise ValueError(f"layout {layout['name']}: request size or feature byte disagrees with features")
        if "version" in layout and layout["fields"][0]["name"] != "version":
            raise ValueError(f"layout {layout['name']}: a versioned snapshot starts with its version byte")
        for group in layout.get("groups", []):
            values = [v["value"] for v in group["values"]]
            if len(set(values)) != len(values):
                raise ValueError(f"layout {layout['name']}: duplicate value in {group['name']}")
            if group.get("flags") and any(v & (v - 1) or v > 255 for v in values):
                raise ValueError(f"layout {layout['name']}: {group['name']} flags must be single byte bits")
    check_fields("settings_snapshot.header", spec["settings_snapshot"]["header"], spec["settings_snapshot"]["header_size"])
    check_fields("cached_report_envelope", spec["cached_report_envelope"], spec["cached_report_envelope_size"])
    usb = spec["usb"]
    if usb["report_count"] * usb["report_size_bits"] != (spec["frame"]["size"] - 1) * 8:
        raise ValueError("usb report_count must cover the frame after its report id")
    if sorted(r["report_id"] for r in usb["report_usages"]) != sorted([spec["control"]["report_id"], spec["rpc"]["report_id"]]):
        raise ValueError("usb report_usages must name reports 2 and 3")


def profile_mask(spec, profile):
    index = {s["name"]: s["index"] for s in spec["settings"]}
    return sum(1 << index[name] for name in profile["controls"])


# ---------------------------------------------------------------- C header

def c_string(data):
    if all(chr(b).isalnum() for b in data):
        return '"' + bytes(data).decode() + '"'
    return "".join('"\\x%02x"' % b for b in data)


def c_value_test(domain, var="value"):
    kind = domain["kind"]
    if kind in ("enum", "toggle"):
        return " || ".join(f"{var}==0x{v['value']:x}u" for v in domain["values"])
    if kind == "percent":
        if "flag" in domain:
            return f"({var}&~0xffu)==0x{domain['flag']:x}u && ({var}&0xffu)<={domain['maximum']}u"
        return f"{var}<={domain['maximum']}u"
    if kind == "mode_mask":
        mask = 0
        for v in domain["values"]:
            mask |= v["value"]
        return f"({var}&~0x{mask:x}u)==0 && dongle_bit_count({var})>={domain['minimum_selected']}u"
    if kind == "action_pair":
        def side(expr):
            return "(" + " || ".join(f"{expr}==0x{v['value']:x}u" for v in domain["values"]) + ")"
        width = 8 * len(domain["sides"])
        tests = [f"{var}<=0x{(1 << width) - 1:x}u"]
        for i in range(len(domain["sides"])):
            tests.append(side(f"(({var}>>{8 * i})&0xffu)" if i else f"({var}&0xffu)"))
        return " && ".join(tests)
    raise ValueError("unknown domain kind " + kind)


def c_defines(prefix, items, fmt="{}"):
    return [f"#define {prefix}{ident(i['name'])} {fmt.format(i['value'])}" for i in items]


def c_fields(prefix, fields):
    lines = []
    for f in fields:
        lines.append(f"#define {prefix}OFFSET_{ident(f['name'])} {f['offset']}")
        if f["size"] != 1:
            lines.append(f"#define {prefix}SIZE_{ident(f['name'])} {f['size']}")
    return lines


def c_number(value):
    if value == -(1 << 31):
        return "INT32_MIN"
    if value < 0:
        return str(value)
    return f"0x{value:x}u" if value > 0xffff else str(value)


def c_layouts(spec):
    out = []
    for layout in spec["layouts"]:
        prefix = "DONGLE_" + ident(layout["name"]) + "_"
        out.append(f"// {layout['comment']}")
        if "version" in layout:
            out.append(f"#define {prefix}VERSION {layout['version']}")
        if "size" in layout:
            out.append(f"#define {prefix}SIZE {layout['size']}u")
        else:
            out.append(f"#define {prefix}REQUEST_SIZE {layout['request_size']}u")
        out += c_fields(prefix, layout["fields"])
        for group in layout.get("groups", []):
            out += [f"#define {prefix}{ident(group['name'])}_{ident(v['name'])} {v['value']}" for v in group["values"]]
        out += [f"#define {prefix}{ident(c['name'])} {c_number(c['value'])}" for c in layout.get("constants", [])]
    return out


def c_usb(spec):
    usb = spec["usb"]
    out = [f"#define DONGLE_USB_VENDOR_ID 0x{usb['vendor_id']:04x}"]
    out += [f"#define DONGLE_USB_PRODUCT_ID_{ident(p['name'])} 0x{p['value']:04x}" for p in usb["products"]]
    out += [f"#define DONGLE_USB_VENDOR_USAGE_PAGE 0x{usb['vendor_usage_page']:04x}",
            f"#define DONGLE_USB_VENDOR_USAGE {usb['vendor_usage']}"]
    out += [f"#define DONGLE_USB_REPORT_USAGE_{ident(r['name'])} {r['usage']}" for r in usb["report_usages"]]
    out += [f"#define DONGLE_USB_REPORT_SIZE_BITS {usb['report_size_bits']}",
            f"#define DONGLE_USB_REPORT_COUNT {usb['report_count']}"]
    return out


def c_header(spec):
    control, rpc, phone, aacp = spec["control"], spec["rpc"], spec["phone_transport"], spec["aacp"]
